export const BUILDING_DEFS: readonly BuildingDef[] = parseBuildingDefs(RAW_BUILDINGS);
export const BUILDING_INDEX: ReadonlyMap<string, number> = new Map(BUILDING_DEFS.map((def, i) => [def.id, i]));

for (const def of BUILDING_DEFS) {
  for (const unit of def.trains) if (!UNIT_INDEX.has(unit)) throw new Error(`Building ${def.id} trains unknown unit ${unit}`);
}

export function buildingIndex(id: string): number {
  const index = BUILDING_INDEX.get(id);
  if (index === undefined) throw new Error(`Unknown building ${id}`);
  return index;
}

/** Buildings of a faction, headquarters first. */
export function buildingsOf(faction: string): BuildingDef[] {
  return BUILDING_DEFS.filter((d) => d.faction === faction).sort((a, b) => Number(b.hq) - Number(a.hq));
}
